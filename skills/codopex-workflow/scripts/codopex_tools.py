#!/usr/bin/env python3
"""Small calculations for the codopex co-doping workflow.

Standard library only. Every subcommand reads plain JSON (or YAML if PyYAML
is installed) or command-line numbers and prints a table; run any subcommand
with -h for its input.

Subcommands
-----------
eb          binding energy E_b(E_F) of complexes from formation-energy intercepts
deltaeb     incremental binding  Delta E_b = E_b(K+X) - E_b(K) - E_b(X)
manybody    departure of a computed E_b from the sum of its contact-pair E_b
tiers       rank scored pairs into priority tiers I / II / III
abundance   dilute-limit fraction of a defect bound into a complex
fermishift  estimate how far a charged species shifts a pinned Fermi level

Conventions
-----------
Formation energies are given as intercepts at E_F = 0 (the VBM), per charge
state, already including finite-size corrections and evaluated at one set of
chemical potentials:  Delta H(q, E_F) = intercept(q) + q * E_F.
E_b does not depend on the chemical potentials, provided the same set is used
for the complex and its constituents.  Energies in eV, temperatures in K.

Interfaces
----------
Point-defect intercepts can be taken from doped (API of doped 3.2):

    df = thermo.get_formation_energies(limit="A", fermi_level=0.0)
    intercepts = intercepts_from_doped(df)      # {defect: {q: E}}

Complex supercells generated by codopex are corrected with the same scheme as
the point defects (for eFNV, e.g. pydefect, with the point charge at the
centroid of the constituents) and added to the input by hand.
"""

from __future__ import annotations

import argparse
import json
import math
import sys

KB = 8.617333262e-5  # eV/K


# ----------------------------------------------------------------- I/O helpers
def load(path: str):
    """Read JSON, or YAML when the file ends in .yaml/.yml and PyYAML exists."""
    with open(path, encoding="utf-8") as fh:
        text = fh.read()
    if path.endswith((".yaml", ".yml")):
        try:
            import yaml  # type: ignore
        except ImportError:  # pragma: no cover
            sys.exit("PyYAML is not installed; give the input as JSON instead.")
        return yaml.safe_load(text)
    return json.loads(text)


def _charges(d: dict) -> dict[int, float]:
    return {int(str(q).replace("+", "")): float(e) for q, e in d.items()}


def intercepts_from_doped(df) -> dict[str, dict[int, float]]:
    """Convert a doped formation-energy table evaluated at E_F = 0.

    ``df`` is the DataFrame returned by
    ``DefectThermodynamics.get_formation_energies(limit=..., fermi_level=0.0)``,
    indexed by (Defect, q) with the formation energy in column "Eᶠᵒʳᵐ".
    Returns {defect name: {charge: intercept}}.
    """
    col = "Eᶠᵒʳᵐ"
    if col not in df.columns:
        raise KeyError(f"column {col!r} not found; columns are {list(df.columns)}")
    out: dict[str, dict[int, float]] = {}
    for (name, q), row in df.iterrows():
        out.setdefault(str(name), {})[int(str(q).replace("+", ""))] = float(row[col])
    return out


# ------------------------------------------------------------------- physics
def formation(intercepts: dict[int, float], ef: float) -> tuple[float, int]:
    """Lowest formation energy and its charge state at Fermi level ef."""
    q, e = min(((q, e0 + q * ef) for q, e0 in intercepts.items()), key=lambda t: t[1])
    return e, q


def binding(defects: dict, complex_name: str, parts: list[str], ef: float):
    """E_b at ef, the charge state of the complex and of each constituent."""
    e_c, q_c = formation(defects[complex_name], ef)
    e_parts, q_parts = 0.0, []
    for p in parts:
        e, q = formation(defects[p], ef)
        e_parts += e
        q_parts.append(q)
    return e_c - e_parts, q_c, q_parts


def fermi_shift_pinned(r: float, kT: float, follows_ef: bool = False) -> float:
    """|Delta E_F| when E_F is pinned by a compensating donor D+ and acceptor A-.

    A singly charged species of concentration r * c_A is added.  With a fixed
    concentration the shift is kT ln[(r + sqrt(r^2 + 4)) / 2]; if its
    concentration follows E_F like the acceptor's (open system) it is
    (kT/2) ln(1 + r).  Both reduce to r kT / 2 for r << 1.
    """
    if follows_ef:
        return 0.5 * kT * math.log1p(r)
    return kT * math.log((r + math.sqrt(r * r + 4.0)) / 2.0)


def fermi_shift_carriers(r: float, kT: float) -> float:
    """|Delta E_F| when E_F is set by free carriers n and r = |q| c_X / n < 1."""
    if r >= 1:
        return float("inf")
    return -kT * math.log1p(-r)


# --------------------------------------------------------------- subcommands
def cmd_eb(a):
    data = load(a.input)
    defects = {k: _charges(v) for k, v in data["defects"].items()}
    gap = float(data.get("gap", a.gap))
    n = max(1, int(round(gap / a.step)))
    grid = [i * gap / n for i in range(n + 1)]
    for cname, parts in data["complexes"].items():
        print(f"# {cname} = {' + '.join(parts)}")
        rows = [(ef, *binding(defects, cname, parts, ef)) for ef in grid]
        if a.csv:
            print("E_F,E_b,q_complex,q_parts")
            for ef, eb, qc, qp in rows:
                print(f"{ef:.3f},{eb:.4f},{qc:+d},{' '.join(f'{q:+d}' for q in qp)}")
        if a.ef_eq is not None:
            eb, qc, qp = binding(defects, cname, parts, a.ef_eq)
            print(f"  at E_F^eq = {a.ef_eq:.3f} eV: E_b = {eb:+.3f} eV, q_complex = {qc:+d}, "
                  f"q_parts = {qp} (sum {sum(qp):+d})")
            if qc != sum(qp):
                print("  note: the complex charge differs from the sum of its constituents; "
                      "check the oxidation states and the Fermi-level self-consistency.")
        ebs = [r[1] for r in rows]
        print(f"  E_b over the gap: {min(ebs):+.3f} to {max(ebs):+.3f} eV")
        bound = [r[0] for r in rows if r[1] < 0]
        if bound:
            print(f"  bound (E_b < 0) somewhere in E_F = {bound[0]:.2f}-{bound[-1]:.2f} eV "
                  f"({len(bound)} of {len(rows)} grid points)")
        else:
            print("  unbound at every Fermi level")


def cmd_deltaeb(a):
    d = a.eb_kx - a.eb_k - a.eb_x
    verdict = "added unit binds: expand further" if d < 0 else "added unit does not bind: stop"
    print(f"Delta E_b = {a.eb_kx:+.3f} - ({a.eb_k:+.3f}) - ({a.eb_x:+.3f}) = {d:+.3f} eV -> {verdict}")
    if a.eb_kx < 0 <= d:
        print("note: E_b(K+X) < 0, yet K+X lies above K and X apart; it is not a grown complex.")


def cmd_manybody(a):
    s = sum(a.pairs)
    dev = a.eb - s
    kind = "anti-cooperative" if dev > 0 else "cooperative"
    print(f"pair-table estimate (sum of contact pairs) = {s:+.3f} eV")
    print(f"computed E_b                               = {a.eb:+.3f} eV")
    print(f"many-body departure                        = {dev:+.3f} eV ({kind})")
    print("The departure combines interactions beyond the contact shell with genuine "
          "three-body (or higher) terms; pairs not in contact were taken as zero.")


def cmd_tiers(a):
    """Input: {"pairs": {"A+B": {"plus": ["HSAB"], "minus": {"HSAB": "reason"}}, ...}}

    "plus" lists the mechanisms favored by the chemical environment of the pair.
    "minus" maps such a mechanism to the precondition its local environment does
    not meet.  A minus without a matching plus is ignored.
    """
    data = load(a.input)
    tiers: dict[str, list[str]] = {"I": [], "II": [], "III": []}
    print(f"{'pair':26s} {'+ (chemical environment)':34s} {'- (local environment)':44s} tier")
    for name, m in data["pairs"].items():
        plus = list(m.get("plus", []))
        minus = dict(m.get("minus", {}))
        ignored = [k for k in minus if k not in plus]
        live = [p for p in plus if p not in minus]
        tier = "III" if not plus else ("I" if live else "II")
        tiers[tier].append(name)
        mtxt = "; ".join(f"{k}: {v}" for k, v in minus.items() if k in plus) or "-"
        print(f"{name:26s} {', '.join(plus) or '-':34s} {mtxt:44s} {tier}")
        if ignored:
            print(f"{'':26s} note: '-' for {ignored} has no matching '+' and is ignored")
    print()
    for t in ("I", "II", "III"):
        print(f"tier {t:3s} ({len(tiers[t])}): {', '.join(tiers[t]) or '-'}")
    print("Compute tier I first, then II, then III as the budget allows; "
          "state explicitly any tier that is skipped.")


def cmd_abundance(a):
    kT = KB * a.T
    print(f"k_B T = {kT:.4f} eV at {a.T:.0f} K, E_b = {a.eb:+.3f} eV, z = {a.z:g}")
    if a.dh_partner is None and a.x_partner is None:
        sys.exit("give --dh-partner (open system), --x-partner (closed system), or both")
    if a.dh_partner is not None:
        f = a.z * math.exp(-(a.dh_partner + a.eb) / kT)
        print(f"open system (fixed chemical potentials, partner Delta H = {a.dh_partner:.3f} eV):")
        print(f"  c_complex / c_free = z exp[-(Delta H_partner + E_b)/kT] = {f:.3e}")
    if a.x_partner is not None:
        ratio = a.z * a.x_partner * math.exp(-a.eb / kT)
        print(f"closed system (partner occupies a fraction x = {a.x_partner:g} of its sites):")
        print(f"  c_complex / c_free = z x exp(-E_b/kT) = {ratio:.3e}; "
              f"bound fraction = {ratio / (1 + ratio):.3f}")
    if a.site_gap is not None:
        frac = a.site_ratio * math.exp(-a.site_gap / kT)
        print(f"site partition: c(complex-forming site)/c(preferred site) = "
              f"{a.site_ratio:g} exp(-{a.site_gap:.3f}/kT) = {frac:.3e}")
        print("  multiply the ratios above by this factor to express the complex as a "
              "fraction of all of the dopant")


def cmd_fermishift(a):
    kT = KB * a.T
    print(f"k_B T = {kT:.4f} eV at {a.T:.0f} K")
    print(f"{'r':>10s} {'fixed c_X':>14s} {'c_X follows E_F':>16s} {'carrier-limited':>16s}")
    for r in a.r:
        c = fermi_shift_carriers(r, kT)
        ctxt = "n/a (r >= 1)" if math.isinf(c) else f"{1e3 * c:.4g} meV"
        print(f"{r:10.3g} {1e3 * fermi_shift_pinned(r, kT):10.4g} meV "
              f"{1e3 * fermi_shift_pinned(r, kT, True):12.4g} meV {ctxt:>16s}")
    print("r = |q_c| c_c / (largest charged term in the neutrality condition).")
    print("If r is above ~0.1, re-solve E_F^eq with the complexes included (doped FermiSolver).")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("eb", help="E_b(E_F) of complexes",
                       description='Input JSON: {"gap": 3.3, "defects": {name: {q: intercept}}, '
                                   '"complexes": {complex_name: [part, part, ...]}}. '
                                   "Each complex must also appear under defects.")
    s.add_argument("input")
    s.add_argument("--ef-eq", type=float, default=None, help="report E_b at this Fermi level")
    s.add_argument("--gap", type=float, default=3.0, help="band gap if not given in the input")
    s.add_argument("--step", type=float, default=0.01)
    s.add_argument("--csv", action="store_true", help="print E_b on the whole grid")
    s.set_defaults(func=cmd_eb)

    s = sub.add_parser("deltaeb", help="incremental binding of an added unit")
    s.add_argument("--eb-kx", type=float, required=True, help="E_b of the grown complex K+X")
    s.add_argument("--eb-k", type=float, required=True, help="E_b of the parent complex K")
    s.add_argument("--eb-x", type=float, default=0.0, help="E_b of X (0 for a single defect)")
    s.set_defaults(func=cmd_deltaeb)

    s = sub.add_parser("manybody", help="departure from the pair-table estimate")
    s.add_argument("--eb", type=float, required=True, help="computed E_b of the complex")
    s.add_argument("--pairs", type=float, nargs="+", required=True,
                   help="E_b of every nearest-neighbour pair in contact inside the complex")
    s.set_defaults(func=cmd_manybody)

    s = sub.add_parser("tiers", help="rank scored pairs into tiers",
                       description=cmd_tiers.__doc__)
    s.add_argument("input")
    s.set_defaults(func=cmd_tiers)

    s = sub.add_parser("abundance", help="dilute-limit bound fraction")
    s.add_argument("--eb", type=float, required=True)
    s.add_argument("--z", type=float, required=True,
                   help="number of distinct partner sites adjacent to the defect")
    s.add_argument("--T", type=float, default=900.0)
    s.add_argument("--dh-partner", type=float, default=None,
                   help="formation energy of the partner defect (open system)")
    s.add_argument("--x-partner", type=float, default=None,
                   help="site fraction occupied by the partner (closed system)")
    s.add_argument("--site-gap", type=float, default=None,
                   help="energy of the complex-forming host site above the preferred one")
    s.add_argument("--site-ratio", type=float, default=1.0,
                   help="number of complex-forming sites per preferred site")
    s.set_defaults(func=cmd_abundance)

    s = sub.add_parser("fermishift", help="Fermi-level shift caused by a charged species")
    s.add_argument("--r", type=float, nargs="+", default=[1e-4, 0.1, 1, 3.4, 10, 100])
    s.add_argument("--T", type=float, default=900.0)
    s.set_defaults(func=cmd_fermishift)

    a = p.parse_args(argv)
    a.func(a)


if __name__ == "__main__":
    main()
